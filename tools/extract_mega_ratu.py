"""Build the Mega Ratu 3D model inputs from the product photo.

Writes:
  public/textures/mega-box-front.png   box front, with the strip hidden by the bottle filled in
  public/textures/mega-box-side.png    plain side panel with the gold band
  public/textures/mega-bottle-label.png  label print on transparent ground
  src/megaRatuProfile.js               bottle outline (radius by height) for a LatheGeometry

Run from the repository root:  python3 tools/extract_mega_ratu.py
"""
import json
import numpy as np
from PIL import Image

SRC = "source/mega-ratu-photo.jpg"
img = Image.open(SRC).convert("RGB")
px = np.array(img).astype(int)
lum = px.mean(axis=2)
# White studio ground: bright and nearly grey (gold highlights are bright but saturated).
is_bg = (lum > 222) & ((px.max(axis=2) - px.min(axis=2)) < 28)

# --- Box front (measured in the photo, in pixels) ---
BX0, BX1, BY0, BY1 = 402, 585, 90, 646
front = px[BY0:BY1, BX0:BX1].copy()
# The bottle hides the right edge of the box, and the card's edge catches light:
# copy a clean column across the whole right strip.
for y in range(0, BY1 - BY0):
    front[y, 568 - BX0:] = front[y, 560 - BX0]
Image.fromarray(front.astype(np.uint8)).resize((378, 1112), Image.LANCZOS).save("public/textures/mega-box-front.png")

# Gold band rows (bright, yellow) on the front, as fractions of the box height.
is_gold = (front[:, :, 0] > 120) & (front[:, :, 1] > 90) & (front[:, :, 0] - front[:, :, 2] > 50)
# The band sits in the bottom fifth; the gold frame around MEGA RATU higher up is excluded.
gold = [i for i in range(int(front.shape[0] * 0.8), front.shape[0]) if is_gold[i].mean() > 0.4]
band = (min(gold) / front.shape[0], max(gold) / front.shape[0]) if gold else (0.93, 0.97)

# --- Side panel: black card with the same gold band ---
SW, SH = 320, 1112
side = np.zeros((SH, SW, 3), np.uint8)
side[:] = (14, 12, 13)
side[:, ::6] = (20, 18, 19)  # faint vertical grain like the printed card
g0, g1 = int(band[0] * SH), int(band[1] * SH)
gold_rgb = np.array(front[(min(gold) + max(gold)) // 2, 60] if gold else (190, 150, 60), np.uint8)

side[g0:g1] = gold_rgb
Image.fromarray(side).save("public/textures/mega-box-side.png")

# --- Bottle outline from its right edge against the white ground ---
AXIS = 630
rows = []
for y in range(140, 700):
    # Rightmost bottle pixel, scanning in from the white ground: glass highlights near the
    # axis are bright too, so scanning out from the axis would stop on them.
    span = ~is_bg[y, AXIS:AXIS + 120]
    if not span.any():
        continue
    right = AXIS + int(np.where(span)[0].max()) + 1
    rows.append((y, right - AXIS))
top_y, bottom_y = rows[0][0], rows[-1][0]
# Smooth the radius a little and sample every 4 px, bottom first.
ys = np.array([r[0] for r in rows]); rs = np.array([r[1] for r in rows], float)
k = np.ones(13) / 13
rs = np.convolve(np.pad(rs, 6, mode="edge"), k, mode="valid")
pts = [(float(r), float(y)) for y, r in zip(ys[::-1][::4], rs[::-1][::4])]

# Where the gold foil ends (first non-gold row below the top on the right edge).
foil_end = top_y
for y in range(top_y, bottom_y):
    c = px[y, AXIS + 10]
    if not (c[0] > 110 and c[1] > 80 and c[0] - c[2] > 40):
        foil_end = y
        if y - top_y > 40:
            break

# --- Label print: keep the bright print, drop the glass ---
LX0, LX1, LY0, LY1 = 605, 660, 450, 580
lab = px[LY0:LY1, LX0:LX1]
l = lab.mean(axis=2)
alpha = np.clip((l - 70) * 3.0, 0, 255).astype(np.uint8)
rgba = np.dstack([lab.astype(np.uint8), alpha])
Image.fromarray(rgba, "RGBA").resize(((LX1 - LX0) * 4, (LY1 - LY0) * 4), Image.LANCZOS).save("public/textures/mega-bottle-label.png")

data = {
    "unitPx": 100,
    "box": {"x0": BX0, "x1": BX1, "y0": BY0, "y1": BY1, "goldBand": band},
    "bottle": {"axisX": AXIS, "topY": int(top_y), "bottomY": int(bottom_y), "foilEndY": int(foil_end),
               "points": pts},
    "label": {"x0": LX0, "x1": LX1, "y0": LY0, "y1": LY1},
}
with open("src/megaRatuProfile.js", "w") as f:
    f.write("// Generated by tools/extract_mega_ratu.py from source/mega-ratu-photo.jpg. Do not edit by hand.\n")
    f.write("export const megaRatu = " + json.dumps(data, indent=1) + ";\n")
print("box band", band, "bottle", top_y, bottom_y, "foil end", foil_end, "points", len(pts))
