"""Writes design/kopi-ratu-feature-cards.svg: three Kopi Ratu feature cards as a layered SVG.

Every element sits on its own named layer (Inkscape layer markup, which Illustrator, Affinity and Figma
read as layers/groups). Text stays live text in the brand fonts: Playfair Display (titles) and Georgia (body).
All copy is taken from the Kopi Ratu pouch (front, back and nutrition table).

Run from the repository root:  python3 design/build_feature_cards.py
"""
from PIL import ImageFont

GELASIO = "videos/kopi-ratu/assets/fonts/gelasio-latin-400-normal.woff2"  # Georgia's metrics, for chip widths
INK, ACCENT, GOLD, WHITE = "#54232F", "#FFF9F0", "#E1B377", "#FFFFFF"
TITLE_FONT = "'Playfair Display', Georgia, serif"
BODY_FONT = "Georgia, 'Gelasio', 'Times New Roman', serif"
W, H = 1800, 900
CARD_W, CARD_H, GAP = 520, 660, 30
X0 = (W - 3 * CARD_W - 2 * GAP) // 2
Y0 = (H - CARD_H) // 2

ICONS = {
    "herb": [  # sprig with three leaves
        "M92 146 C92 122 96 100 110 82",
        "M92 128 C74 126 66 112 68 98 C84 100 92 112 92 128 Z",
        "M96 110 C112 110 122 98 120 84 C104 84 96 96 96 110 Z",
        "M106 90 C98 78 102 66 114 60 C120 72 116 84 106 90 Z",
    ],
    "sugar": [  # sugar cube with a downward arrow
        "M80 86 L102 97 L80 108 L58 97 Z",
        "M58 97 V125 L80 136 L102 125 V97",
        "M80 108 V136",
        "M124 88 V130", "M114 120 L124 132 L134 120",
    ],
    "cup": [  # cup on a saucer with steam
        "M62 106 H112 V118 C112 134 100 142 87 142 C74 142 62 134 62 118 Z",
        "M112 110 C127 110 127 128 112 128",
        "M54 150 H120",
        "M78 96 C71 88 84 81 77 72", "M95 96 C88 88 101 81 94 72",
    ],
}

CARDS = [
    {"id": "herba", "icon": "herb", "title": "Campuran Herba",
     "body": ["Kopi pra-campuran dengan", "ginseng, maca, damiana", "dan tongkat ali."],
     "chip": "4 herba pilihan"},
    {"id": "manis", "icon": "sugar", "title": "Kurang Manis",
     "body": ["Rasa rendah gula, dinikmati", "panas dengan aroma yang", "memukau."],
     "chip": "5.7 g gula / hidangan"},
    {"id": "bancuh", "icon": "cup", "title": "Mudah Dibancuh",
     "body": ["Bancuh satu paket dengan", "100–150 ml air panas", "mendidih, kacau hingga rata."],
     "chip": "15 hidangan sebungkus"},
]

chip_font = ImageFont.truetype(GELASIO, 21)


def layer(lid, label, inner, transform=""):
    t = f' transform="{transform}"' if transform else ""
    return (f'<g id="{lid}" inkscape:groupmode="layer" inkscape:label="{label}"{t}>\n'
            + "\n".join("  " + line for line in inner.splitlines()) + "\n</g>")


def card(i, c):
    p = c["id"]
    parts = [
        layer(f"{p}-shape", "Card shape",
              f'<rect width="{CARD_W}" height="{CARD_H}" rx="28" fill="url(#card-gradient)"/>'),
        layer(f"{p}-outline", "Card outline",
              f'<rect x="0.75" y="0.75" width="{CARD_W - 1.5}" height="{CARD_H - 1.5}" rx="27.25" '
              f'fill="none" stroke="{INK}" stroke-opacity="0.14" stroke-width="1.5"/>'),
        layer(f"{p}-icon-badge", "Icon badge",
              f'<circle cx="92" cy="112" r="58" fill="{ACCENT}" stroke="{INK}" stroke-opacity="0.15" stroke-width="1.5"/>'),
        layer(f"{p}-icon", "Icon",
              f'<g fill="none" stroke="{INK}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">\n'
              + "\n".join(f'  <path d="{d}"/>' for d in ICONS[c["icon"]]) + "\n</g>"),
        layer(f"{p}-title", "Title",
              f'<text x="48" y="262" font-family="{TITLE_FONT}" font-weight="700" font-size="46" '
              f'fill="{INK}">{c["title"]}</text>'),
        layer(f"{p}-rule", "Rule", f'<rect x="48" y="292" width="64" height="3" fill="{INK}"/>'),
        layer(f"{p}-body", "Body text",
              f'<text font-family="{BODY_FONT}" font-size="25" fill="{INK}">\n'
              + "\n".join(f'  <tspan x="48" y="{352 + k * 38}">{line}</tspan>' for k, line in enumerate(c["body"]))
              + "\n</text>"),
    ]
    label = c["chip"].upper()
    tw = chip_font.getlength(label) + 1.5 * (len(label) - 1)
    cw = round(tw + 48)
    parts += [
        layer(f"{p}-chip", "Detail chip", f'<rect x="48" y="560" width="{cw}" height="50" rx="25" fill="{INK}"/>'),
        layer(f"{p}-chip-text", "Detail text",
              f'<text x="72" y="592" font-family="{BODY_FONT}" font-size="21" letter-spacing="1.5" '
              f'fill="{ACCENT}">{label}</text>'),
    ]
    x = X0 + i * (CARD_W + GAP)
    return layer(f"card-{p}", f"Card {i + 1} · {c['title']}", "\n".join(parts), f"translate({x} {Y0})")


svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Kopi Ratu feature cards. Generated by design/build_feature_cards.py. Fonts: Playfair Display, Georgia. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
     width="{W}" height="{H}" viewBox="0 0 {W} {H}">
<title>Kopi Ratu feature cards</title>
<defs>
  <linearGradient id="card-gradient" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{WHITE}"/>
    <stop offset="0.55" stop-color="{WHITE}"/>
    <stop offset="1" stop-color="{GOLD}"/>
  </linearGradient>
</defs>
{layer("background", "Background", f'<rect width="{W}" height="{H}" fill="{ACCENT}"/>')}
{chr(10).join(card(i, c) for i, c in enumerate(CARDS))}
</svg>
'''
open("design/kopi-ratu-feature-cards.svg", "w", encoding="utf-8").write(svg)
print("wrote design/kopi-ratu-feature-cards.svg", len(svg), "bytes")
